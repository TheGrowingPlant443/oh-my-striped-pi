#!/usr/bin/env bun
/**
 * Build the self-contained HTML export viewer, including Markdown and shared React tool/trace views.
 * Local `bun run gen:export-viewer` updates the committed viewer metadata and inline source;
 * CI and `--check` verify the metadata before regenerating the same assets.
 */
import * as fs from "node:fs/promises";
import * as path from "node:path";
import { isDeepStrictEqual } from "node:util";
import { exportThemeStyles, webExportThemeVars } from "../../coding-agent/src/export/html/web-palette";

const collabDir = path.join(import.meta.dir, "..");
const agentDir = path.join(collabDir, "../coding-agent");
const htmlDir = path.join(agentDir, "src/export/html");

/** Exact bytes pinned by the generated manifest. */
export interface ExportViewerMetadata {
	file: string;
	integrity: string;
	size: number;
}

/** Build output locations and metadata verification policy for CI or local generation. */
export interface ExportViewerBuildOptions {
	/** Defaults to coding-agent/export-assets. A custom directory also isolates metadata. */
	outDir?: string;
	/** Defaults to the committed source manifest, or outDir/viewer.generated.json for a custom outDir. */
	metadataPath?: string;
	/** Verify committed metadata and inline source before writing build output. */
	check?: boolean;
}

/** Generate the inline viewer source and one exact-byte-hashed viewer asset. */
export async function buildExportViewer(options: ExportViewerBuildOptions = {}): Promise<ExportViewerMetadata> {
	const outDir = options.outDir ?? path.join(agentDir, "export-assets");
	const metadataPath = options.metadataPath ?? path.join(options.outDir ?? htmlDir, "viewer.generated.json");
	const inlinePath = path.join(options.outDir ?? htmlDir, "viewer.generated.js.txt");
	const result = await Bun.build({
		entrypoints: [path.join(collabDir, "src/export-standalone.ts")],
		root: collabDir,
		target: "browser",
		format: "iife",
		minify: true,
		define: { "process.env.NODE_ENV": JSON.stringify("production") },
	});
	if (!result.success) throw new AggregateError(result.logs, "Export viewer React bundle failed");

	let js = "";
	let css = "";
	for (const artifact of result.outputs) {
		if (artifact.path.endsWith(".css")) css += await artifact.text();
		else if (artifact.path.endsWith(".js")) js += await artifact.text();
		else throw new Error(`Unexpected external export viewer asset: ${artifact.path}`);
	}
	if (!js) throw new Error("Export viewer bundle produced no JavaScript");

	const [shell, templateCss, highlightJs, templateJs] = await Promise.all(
		["shell.html", "template.css", "vendor/highlight.min.js", "template.js"].map(file =>
			Bun.file(path.join(htmlDir, file)).text(),
		),
	);
	const themeCss = exportThemeStyles(webExportThemeVars("dark"), webExportThemeVars("light"));
	// JSON strings preserve arbitrary HTML/CSS without template-literal interpolation.
	const source = [
		"// Generated by packages/collab-web/scripts/build-export-viewer.ts - DO NOT EDIT",
		";(function() {",
		"try {",
		`;(function() {${highlightJs}\n;globalThis.hljs = hljs;})();`,
		"const style = document.createElement('style');",
		"style.dataset.ompExportViewer = '';",
		`style.textContent = ${JSON.stringify(`${themeCss}\n${templateCss}\n${css}`)};`,
		// Custom per-export themes already in the head must retain cascade priority.
		"document.head.prepend(style);",
		js,
		";",
		// Register custom elements before mounting the shell or assigning session data.
		"const sessionData = document.getElementById('session-data');",
		"if (!sessionData) throw new Error('Missing session data');",
		"const shell = document.createElement('template');",
		`shell.innerHTML = ${JSON.stringify(shell)};`,
		"sessionData.parentNode.insertBefore(shell.content, sessionData);",
		templateJs,
		";document.getElementById('viewer-status')?.remove();",
		"} catch (error) {",
		"const status = document.getElementById('viewer-status');",
		"if (status) status.textContent = 'Failed to load viewer: ' + (error instanceof Error ? error.message : String(error));",
		"}",
		"})();",
		"",
	].join("\n");
	const bytes = Buffer.from(source, "utf8");
	const digest = Bun.SHA256.hash(bytes, "hex");
	const metadata: ExportViewerMetadata = {
		file: `export-viewer-${digest}.js`,
		integrity: `sha256-${Buffer.from(digest, "hex").toBase64()}`,
		size: bytes.length,
	};

	if (options.check) {
		const existing: unknown = await Bun.file(metadataPath).json();
		if (!isDeepStrictEqual(existing, metadata)) {
			throw new Error(
				"Export viewer metadata is stale; run bun run gen:export-viewer locally and commit viewer.generated.json and viewer.generated.js.txt",
			);
		}
		if ((await Bun.file(inlinePath).text()) !== source) {
			throw new Error(
				"Export viewer inline source is stale; run bun run gen:export-viewer locally and commit viewer.generated.js.txt",
			);
		}
	}
	await fs.mkdir(outDir, { recursive: true });
	await Bun.write(path.join(outDir, metadata.file), bytes);
	if (!options.check) await Bun.write(inlinePath, source);
	if (!options.check) await Bun.write(metadataPath, `${JSON.stringify(metadata, null, "\t")}\n`);
	// Only discard our obsolete content-addressed files, never other build outputs.
	for (const entry of await fs.readdir(outDir, { withFileTypes: true })) {
		if (entry.isFile() && /^export-viewer-[a-f0-9]{64}\.js$/.test(entry.name) && entry.name !== metadata.file) {
			await fs.unlink(path.join(outDir, entry.name));
		}
	}
	return metadata;
}

if (import.meta.main) {
	const metadata = await buildExportViewer({ check: process.argv.includes("--check") || process.env.CI === "true" });
	console.log(`Generated ${metadata.file} (${(metadata.size / 1024).toFixed(1)} KiB)`);
}
